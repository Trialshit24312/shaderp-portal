export function isAuthConfigured(env) {
  return !!(env.DISCORD_CLIENT_ID && env.DISCORD_GUILD_ID && env.DISCORD_CALLBACK_URL);
}

export function isOAuthReady(env) {
  return isAuthConfigured(env) && !!env.DISCORD_CLIENT_SECRET;
}

